# Builds the bob. wordmark (SVG files + React paths) from Inter ExtraBold outlines
# (byline in Geist Medium, the app font).
# Run from the repo root after `pip install fonttools`: python3 scripts/build-wordmark.py
from fontTools.ttLib import TTFont
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.boundsPen import BoundsPen
from fontTools.pens.transformPen import TransformPen
import json, os

GEIST = "node_modules/geist/dist/fonts/geist-sans/"
LIGHT, DARK, DOT = "#FAF9F6", "#141210", "#FF821C"
SUB_LIGHT, SUB_DARK = "#A8A19A", "#6B655F"

def outline(fontfile, text, tracking, scale=1.0, dx=0, dy=0):
    f = TTFont(fontfile); gs = f.getGlyphSet(); cmap = f.getBestCmap(); upm = f["head"].unitsPerEm
    s = scale * 1000 / upm
    x = 0; d = []; bb = [1e9, 1e9, -1e9, -1e9]
    for i, ch in enumerate(text):
        g = gs[cmap[ord(ch)]]
        m = (s, 0, 0, -s, dx + x * s, dy)
        pen = SVGPathPen(gs, ntos=lambda v: ("%.1f" % v).rstrip("0").rstrip("."))
        g.draw(TransformPen(pen, m)); d.append(pen.getCommands())
        bp = BoundsPen(gs); g.draw(TransformPen(bp, m))
        if bp.bounds:
            b = bp.bounds; bb = [min(bb[0], b[0]), min(bb[1], b[1]), max(bb[2], b[2]), max(bb[3], b[3])]
        x += g.width + (tracking * upm if i < len(text) - 1 else 0)
    return " ".join(d), bb

# Wordmark: Inter ExtraBold, tracked tight (-0.045em) by eye against the
# reference; dot = 30% of letter height, small gap, on the baseline.
# units = 1/1000 em. Inter ships with most Linux distros or from rsms.me/inter.
FONT = os.environ.get("WORDMARK_FONT", "/usr/share/fonts/opentype/inter/Inter-ExtraBold.otf")
TARGET_RATIO = 2.30
_, b0 = outline(FONT, "bob", 0.0)
h0 = max(b0[3], 0) - b0[1]
tracking = ((TARGET_RATIO * h0) - (b0[2] - b0[0])) / 2 / 1000   # two gaps
tracking = float(os.environ.get("WORDMARK_TRACKING", "-0.045"))
letters, bb = outline(FONT, "bob", tracking)
h = max(bb[3], 0) - bb[1]
r = 0.30 * h / 2                 # dot ~30% of letter height
gap = 0.08 * h
cx, cy = bb[2] + gap + r, -r     # sits on the baseline, low beside the final b
minx = round(bb[0]); top = round(bb[1]); bottom = round(max(bb[3], r * 0 + bb[3], 0))
right = round(cx + r + 0.03 * h)   # breathing room so the dot is never clipped by pixel rounding
W, H = right - minx, bottom - top

# Byline beneath, left-aligned, outlined Geist Medium
by_size = H * 0.25
sub, sbb = outline(GEIST + "Geist-Medium.ttf", "by Cresaro", 0.0, scale=by_size / 1000, dx=minx, dy=0)
gap_y = H * 0.16
shift = bottom + gap_y - sbb[1]
sub, sbb = outline(GEIST + "Geist-Medium.ttf", "by Cresaro", 0.0, scale=by_size / 1000, dx=minx + 8, dy=shift)
H2 = round(sbb[3]) - top
W2 = max(W, round(sbb[2]) - minx)

def svg(letter, byline=None):
    vb = f"{minx} {top} {W2 if byline else W} {H2 if byline else H}"
    extra = f'<path fill="{byline}" d="{sub}"/>' if byline else ""
    title = "bob. by Cresaro" if byline else "bob."
    return (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="{vb}" role="img" aria-label="{title}"><title>{title}</title>'
            f'<path fill="{letter}" d="{letters}"/><circle fill="{DOT}" cx="{cx:.1f}" cy="{cy:.1f}" r="{r:.1f}"/>{extra}</svg>\n')

out = os.environ.get("WORDMARK_OUT", "public/brand/")
files = {
    "bob-wordmark.svg": svg(LIGHT),
    "bob-wordmark-dark.svg": svg(DARK),
    "bob-wordmark-by-cresaro.svg": svg(LIGHT, SUB_LIGHT),
    "bob-wordmark-by-cresaro-dark.svg": svg(DARK, SUB_DARK),
}
for n, c in files.items(): open(out + n, "w").write(c)

ts = f'''// Generated by scripts/build-wordmark.py from Inter ExtraBold outlines. Do not edit by hand:
// the shapes must stay identical to public/brand/bob-wordmark*.svg.
export const WORDMARK = {{
  letters: "{letters}",
  dot: {{ cx: {cx:.1f}, cy: {cy:.1f}, r: {r:.1f} }},
  viewBox: "{minx} {top} {W} {H}",
  viewBoxWithByline: "{minx} {top} {W2} {H2}",
  byline: "{sub}",
  ratio: {W / H:.4f},
  ratioWithByline: {W2 / H2:.4f},
}} as const;

export const WORDMARK_COLORS = {{ light: "{LIGHT}", dark: "{DARK}", dot: "{DOT}", bylineOnDark: "{SUB_LIGHT}", bylineOnLight: "{SUB_DARK}" }} as const;
'''
open(os.environ.get("WORDMARK_TS", "src/components/brand/wordmark-paths.ts"), "w").write(ts)
print(dict(tracking=round(tracking,4), W=W, H=H, W2=W2, H2=H2, r=r, cx=cx), {k: len(v) for k, v in files.items()})
